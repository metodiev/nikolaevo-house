def s_rect(c: Canvas, x, y, size, cls="el") -> None:
    c.rect(x - size / 2, y - size / 2, size, size, cls)


def s_socket(c: Canvas, x, y, double: bool = False) -> None:
    """Контакт — полукръг, обърнат към стаята (означен с две черти)."""
    r = 130
    c.circle(x, y, r, "el")
    c.line(x - r * 0.55, y, x + r * 0.55, y, "el-d")
    if double:
        c.circle(x + r * 2.1, y, r, "el")
        c.line(x + r * 2.1 - r * 0.55, y, x + r * 2.1 + r * 0.55, y, "el-d")


def s_switch(c: Canvas, x, y) -> None:
    """Ключ — кръг с радиална черта."""
    r = 120
    c.circle(x, y, r, "el")
    c.line(x, y, x + r * 1.9, y - r * 1.9, "el-d")


def s_light(c: Canvas, x, y, kind="ceil") -> None:
    """Осветително тяло — кръг с кръст."""
    r = 190 if kind == "ceil" else 120
    c.circle(x, y, r, "el")
    c.line(x - r, y - r, x + r, y + r, "el-d")
    c.line(x - r, y + r, x + r, y - r, "el-d")


def s_text_box(c: Canvas, x, y, text, w=520, h=300) -> None:
    c.rect(x - w / 2, y - h / 2, w, h, "el")
    c.text(x, y + 90, text, "lbl-f")


def s_board(c: Canvas, x, y) -> None:
    c.rect(x - 300, y - 110, 600, 220, "el-f")


def s_fan(c: Canvas, x, y) -> None:
    r = 170
    c.circle(x, y, r, "el")
    c.line(x - r, y, x + r, y, "el-d")
    c.line(x, y - r, x, y + r, "el-d")


def draw_point(c: Canvas, x, y, kind: str) -> None:
    if kind == "s1":
        s_socket(c, x, y, False)
    elif kind == "s2":
        s_socket(c, x, y, True)
    elif kind == "ip":
        s_socket(c, x, y, False)
        c.text(x, y - 260, "IP44", "lbl-f")
    elif kind == "sw":
        s_switch(c, x, y)
    elif kind == "tv":
        s_text_box(c, x, y, "ТВ")
    elif kind == "lan":
        s_text_box(c, x, y, "LAN")
    elif kind == "brd":
        s_board(c, x, y)
    elif kind == "fan":
        s_fan(c, x, y)
    elif kind == "bell":
        s_text_box(c, x, y, "ЗВ", 420, 280)



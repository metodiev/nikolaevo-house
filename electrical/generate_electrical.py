def build_schematic() -> Canvas:
    """Едносхемна схема — чертае се в милиметри хартия (мащаб 1:1)."""
    c = Canvas(1, "E-02 Едносхемна схема на таблото")

    def box(x, y, w, h, title, sub="", cls="el") -> None:
        c.rect(x, y, w, h, cls)
        c.text(x + w / 2, y + h / 2 + (-1.0 if sub else 1.0), title, "note")
        if sub:
            c.text(x + w / 2, y + h / 2 + 5.0, sub, "lbl-s")

    y0 = 30.0
    c.text(12, 18, "ЗАХРАНВАНЕ И ТАБЛО", "sub", "start")

    box(12, y0, 40, 20, "Захранване", "3×25 A · TN-C-S")
    c.line(52, y0 + 10, 60, y0 + 10, "el-d")
    box(60, y0, 40, 20, "Главен прекъсвач", "40 A / 3P")
    c.line(100, y0 + 10, 108, y0 + 10, "el-d")
    box(108, y0, 40, 20, "ПРЗ тип 2", "пренапрежение")

    # шина
    bus_x = 158.0
    c.line(148, y0 + 10, bus_x, y0 + 10, "el-d")
    c.line(bus_x, y0 - 2, bus_x, y0 + 30, "el-d")

    box(bus_x + 6, y0 - 4, 34, 15, "ДЗТ 1", "40 A / 30 mA")
    box(bus_x + 6, y0 + 19, 34, 15, "ДЗТ 2", "40 A / 30 mA")
    c.line(bus_x, y0 - 4 + 7.5, bus_x + 6, y0 - 4 + 7.5, "el-d")
    c.line(bus_x, y0 + 19 + 7.5, bus_x + 6, y0 + 19 + 7.5, "el-d")

    # --- таблица на кръговете ----------------------------------------------
    ty = 66.0
    cols = [(12, 8, "№"), (20, 108, "кръг"), (128, 22, "защита"),
            (150, 24, "кабел"), (174, 24, "ДЗТ")]
    c.line(12, ty, 198, ty, "wall-l")
    for x, w, head in cols:
        c.text(x + 1.5, ty + 5, head, "lbl-s", "start")
    c.line(12, ty + 7, 198, ty + 7, "wall-l")

    row_h = 9.4
    for i, (code, desc, amps, cable) in enumerate(CIRCUITS):
        y = ty + 7 + i * row_h
        rcd = "ДЗТ 1" if i < 6 else "ДЗТ 2"
        c.text(cols[0][0] + 1.5, y + 6, code, "note", "start")
        c.text(cols[1][0] + 1.5, y + 6, desc, "note", "start")
        c.text(cols[2][0] + 1.5, y + 6, amps, "note", "start")
        c.text(cols[3][0] + 1.5, y + 6, cable, "note", "start")
        c.text(cols[4][0] + 1.5, y + 6, rcd, "note", "start")
        c.line(12, y + row_h, 198, y + row_h, "dim")

    # --- бележки ------------------------------------------------------------
    ny = ty + 7 + len(CIRCUITS) * row_h + 10
    c.text(12, ny, "БЕЛЕЖКИ", "sub", "start")
    notes = [
        "1. Схемата е концептуална. Оразмеряването на кабелите, защитите и",
        "    селективността се прави от лицензиран проектант по действащите норми.",
        "2. ДЗТ 2 обхваща мокрите помещения и външните консуматори (30 mA).",
        "3. Кухнята (котлони, фурна) е на отделен кръг — не се комбинира с контактите.",
        "4. Таблото е в антрето, на южната стена до вратата, на височина 1400–1800 mm.",
        "5. Свободните места в таблото се предвиждат за резервни кръгове.",
    ]
    for i, text in enumerate(notes):
        c.text(12, ny + 7 + i * 5.0, text, "note", "start")

    c.title_block(
        12, ny + 38, 186,
        [
            "NIKOLAEVO HOUSE — ЕЛЕКТРОИНСТАЛАЦИЯ",
            "Едносхемна схема на таблото · лист E-02",
            "Концепция — не е работна схема. Подлежи на съгласуване с ЕРП и проектант.",
        ],
        "E-02",
        "Без мащаб",
    )
    return c



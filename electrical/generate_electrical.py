def draw_shell(c: Canvas) -> None:
    c.rect(0, 0, L, T, "wall")
    c.rect(0, D - T, L, T, "wall")
    c.rect(0, T, T, D - 2 * T, "wall")
    c.rect(L - T, T, T, D - 2 * T, "wall")
    for x1, y1, x2, y2 in WINDOWS:
        c.rect(x1, y1, x2 - x1, y2 - y1, "win")
    for x1, y1, x2, y2 in PARTITIONS:
        c.rect(x1, y1, x2 - x1, y2 - y1, "part")
    for x1, y1, x2, y2, _ in DOORS:
        c.rect(x1, y1, x2 - x1, y2 - y1, "win")


def build_plan() -> Canvas:
    c = Canvas(75, "E-01 Електроинсталация — план 1:75")
    u = c.u

    draw_shell(c)

    for x, y, kind in POINTS:
        draw_point(c, x, y, kind)
    for x, y, kind in LIGHTS:
        s_light(c, x, y, kind)

    for key, name in (("bath", "БАНЯ"), ("wet", "МОКРО"), ("corr", "КОРИДОР"),
                      ("bed1", "СПАЛНЯ 1"), ("bed2", "СПАЛНЯ 2"),
                      ("entry", "АНТРЕ")):
        x1, y1, x2, y2 = ROOMS[key]
        c.text((x1 + x2) / 2, y2 - 220, name, "lbl-s")
    c.text(8300, 7000, "ХОЛ + ТРАПЕЗАРИЯ + КУХНЯ", "lbl-s")

    # легенда — долу вляво, в две колони
    ly = D + u(10)
    c.text(0, ly, "ЛЕГЕНДА", "sub", "start")
    items = [
        ("s1", "контакт единичен"),
        ("s2", "контакт двоен"),
        ("ip", "контакт IP44"),
        ("sw", "ключ"),
        ("light", "осветително тяло"),
        ("spot", "акцентно осветление"),
        ("fan", "вентилатор"),
        ("tv", "ТВ / LAN извод"),
        ("brd", "табло"),
    ]
    for i, (kind, text) in enumerate(items):
        col = i // 5
        row = i % 5
        x = col * u(78)
        y = ly + u(10) + row * u(8.0)
        if kind == "light":
            s_light(c, x + u(5), y - u(1), "ceil")
        elif kind == "spot":
            s_light(c, x + u(5), y - u(1), "spot")
        elif kind == "brd":
            s_board(c, x + u(5), y - u(1))
        elif kind == "tv":
            s_text_box(c, x + u(5), y - u(1), "ТВ", 460, 260)
        else:
            draw_point(c, x + u(5), y - u(1), kind)
        c.text(x + u(13), y, text, "note", "start")

    c.title_block(
        -u(3), ly + u(50), L + u(14),
        [
            "NIKOLAEVO HOUSE — ЕЛЕКТРОИНСТАЛАЦИЯ",
            "План на контакти, ключове и осветление · лист E-01",
            "Табло в антрето, на южната стена до вратата (височина 1400–1800 mm).",
            "Концепция за разполагане — сеченията и защитите се определят от проектант.",
            "Размери в mm. Ключовете за банята и мокрото са отвън, в коридора.",
        ],
        "E-01",
        "Мащаб 1:75",
    )
    return c



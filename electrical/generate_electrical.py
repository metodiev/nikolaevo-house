def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    jobs = [
        (build_plan, "E-01-plan.svg", (-px(0.8), -px(0.6), px(13.4), px(16.3))),
        (build_schematic, "E-02-tablo.svg", (-14, -8, 240, 282)),
    ]
    print("Електро — записани файлове:")
    for builder, name, viewbox in jobs:
        path = builder().render(viewbox, OUT / name)
        print(f"  {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
